#include "3-calc.h"

/**
 * op_add - Returns a + b
 * @a: First integer
 * @b: Second integer
 * Return: a + b
 */
int op_add(int a, int b)
{
	return (a + b);
}

/**
 * op_sub - Returns a - b
 * @a: First integer
 * @b: Second integer
 * Return: a - b
 */
int op_sub(int a, int b)
{
	return (a - b);
}

/**
 * op_mul - Returns a * b
 * @a: First integer
 * @b: Second integer
 * Return: a * b
 */
int op_mul(int a, int b)
{
	return (a * b);
}

/**
 * op_div - Returns a / b
 * @a: First integer
 * @b: Second integer
 * Return: a / b
 */
int op_div(int a, int b)
{
	return (a / b);
}

/**
 * op_mod - Returns a / b remainder
 * @a: First integer
 * @b: Second integer
 * Return: a % b
 */
int op_mod(int a, int b)
{
	return (a % b);
}
