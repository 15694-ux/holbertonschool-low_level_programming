#include <stdio.h>
#include <ctype.h>
#include <string.h>

/**
 * main - Entry point of the program
 *
 * Return: Always 0 (Success)
 */

int main(void)

{
	char ch;
	int i;

	for (i = '0'; i <= '9'; i++)
		putchar(ch);

	for (ch = 'a'; ch <= 'a'; ch++)
		putchar(i);
		putchar(ch);


	putchar('\n');
	return (0);
}
